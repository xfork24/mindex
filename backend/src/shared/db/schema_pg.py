"""PostgreSQL 基线 schema（plans §5）：对应当前 metadata 库逻辑 schema 的全表 DDL。

与 SQLite 的映射约定：

- 每张表都有显式 ``rowid BIGINT GENERATED BY DEFAULT AS IDENTITY`` 列，业务 SQL 里的
  ``ORDER BY rowid`` / ``WHERE rowid=?`` / ``max(rowid)`` 原文可用；``INSERT OR
  REPLACE`` 改写会用 ``SET rowid=DEFAULT`` 复现「替换后移到末尾」的语义。SQLite 中
  ``INTEGER PRIMARY KEY`` 即 rowid 的表（model_profiles/voices/runs）不另建 rowid 列。
- ``REAL`` → ``DOUBLE PRECISION``（同为 8 字节双精度）、``BLOB`` → ``BYTEA``、
  JSON 列保持 ``TEXT`` 原文（plans §5：不做全库 JSONB 改写）。
- ``CURRENT_TIMESTAMP`` 默认值显式格式化为与 SQLite 一致的 UTC
  ``YYYY-MM-DD HH:MM:SS`` 文本。
- 保留字列名 ``end`` 带引号；其余标识符全小写（PG 折叠规则）。
- 该 DDL 只作为**新库基线**由 ``migrate_pg`` 应用；SQLite 的历史迁移步骤保持原样，
  以后新增逻辑版本时两侧同步追加（共用逻辑版本号，允许后端空操作）。
"""

