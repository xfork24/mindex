# delivery_platforms 的种子数据沿用 _metadata_v8：只在基线迁移时写入（幂等）。
def DELIVERY_PLATFORMS_SEED(dumps):  # pragma: no cover - 与 SQLite 迁移共用同一份 YAML
    from pathlib import Path

    import yaml

    rows = []
    for key in ("bilibili", "douyin", "youtube"):
        source = Path(__file__).resolve().parent.parent.parent / "studio" / "platforms" / f"{key}.yaml"
        body = yaml.safe_load(source.read_text(encoding="utf-8"))
        rows.append((key, dumps(body), "2026-01-01T00:00:00", "2026-01-01T00:00:00"))
    return rows
